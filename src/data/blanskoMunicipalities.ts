/**
 * Rychlé vyhledávání v obcích a městech okresu Blansko
 */
export function searchBlanskoMunicipalities(query: string): BlanskoMunicipality[] {
  if (!query || !query.trim()) return BLANSKO_MUNICIPALITIES;

  const normalize = (s: string) =>
    (s || '')
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .toLowerCase()
      .trim();

  const q = normalize(query);

  return BLANSKO_MUNICIPALITIES.filter((item) => {
    const n = normalize(item.name);
    const h = normalize(item.cyclingHighlight || '');
    const d = normalize(item.description || '');
    const t = normalize(item.type);
    return n.includes(q) || h.includes(q) || d.includes(q) || t.includes(q);
  });
}
